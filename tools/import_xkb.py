class RuleNames(C.Structure):
    _fields_ = [(key, C.c_char_p) for key in ("rules", "model", "layout", "variant", "options")]


class XKB:
    """Small typed binding; ownership of keymaps/states stays explicit."""

    def __init__(self, source):
        lib = C.CDLL("libxkbcommon.so.0")
        p, u, s, n = C.c_void_p, C.c_uint, C.c_char_p, C.c_size_t
        signatures = {
            "context_new": (p, [C.c_int]),
            "context_unref": (None, [p]),
            "context_include_path_clear": (None, [p]),
            "context_include_path_append": (C.c_int, [p, s]),
            "context_set_log_level": (None, [p, C.c_int]),
            "keymap_new_from_names": (p, [p, C.POINTER(RuleNames), C.c_int]),
            "keymap_unref": (None, [p]),
            "keymap_key_by_name": (u, [p, s]),
            "keymap_key_get_name": (s, [p, u]),
            "keymap_min_keycode": (u, [p]),
            "keymap_max_keycode": (u, [p]),
            "keymap_num_layouts_for_key": (u, [p, u]),
            "keymap_num_levels_for_key": (u, [p, u, u]),
            "keymap_key_get_syms_by_level": (C.c_int, [p, u, u, u, C.POINTER(C.POINTER(u))]),
            "keysym_get_name": (C.c_int, [u, s, n]),
            "keysym_to_utf32": (u, [u]),
            "state_new": (p, [p]),
            "state_unref": (None, [p]),
            "state_update_key": (u, [p, u, C.c_int]),
            "state_key_get_syms": (C.c_int, [p, u, C.POINTER(C.POINTER(u))]),
            "state_key_get_layout": (u, [p, u]),
            "state_key_get_level": (u, [p, u, u]),
            "state_serialize_mods": (u, [p, u]),
            "state_serialize_layout": (u, [p, u]),
            "compose_table_new_from_buffer": (p, [p, s, n, s, C.c_int, C.c_int]),
            "compose_table_unref": (None, [p]),
            "compose_table_iterator_new": (p, [p]),
            "compose_table_iterator_next": (p, [p]),
            "compose_table_iterator_free": (None, [p]),
            "compose_table_entry_sequence": (C.POINTER(u), [p, C.POINTER(n)]),
            "compose_table_entry_utf8": (s, [p]),
            "compose_state_new": (p, [p, C.c_int]),
            "compose_state_unref": (None, [p]),
            "compose_state_feed": (C.c_int, [p, u]),
            "compose_state_reset": (None, [p]),
            "compose_state_get_status": (C.c_int, [p]),
            "compose_state_get_utf8": (C.c_int, [p, s, n]),
        }
        for name, (result, args) in signatures.items():
            func = getattr(lib, "xkb_" + name)
            func.restype, func.argtypes = result, args
            setattr(self, name, func)
        # NO_DEFAULT_INCLUDES | NO_ENVIRONMENT_NAMES: ignore personal config.
        self.context = self.context_new(3)
        self.context_include_path_clear(self.context)
        if not self.context_include_path_append(self.context, os.fsencode(source)):
            raise RuntimeError(f"Cannot load XKB data from {source}")
        self.context_set_log_level(self.context, 10)  # errors only
        compose_path = Path("/usr/share/X11/locale/en_US.UTF-8/Compose")
        compose = compose_path.read_bytes()
        self.table = self.compose_table_new_from_buffer(
            self.context, compose, len(compose), b"C.UTF-8", 1, 0)
        if not self.table:
            raise RuntimeError("Cannot compile system Compose table")
        self.compose_hash = hashlib.sha256(compose).hexdigest()
        self.compose_state = self.compose_state_new(self.table, 0)
        self.entries = []
        iterator = self.compose_table_iterator_new(self.table)
        try:
            while True:
                entry = self.compose_table_iterator_next(iterator)
                if not entry:
                    break
                count = C.c_size_t()
                symbols = self.compose_table_entry_sequence(entry, C.byref(count))
                output = self.compose_table_entry_utf8(entry).decode()
                if output and output.isprintable():
                    self.entries.append((tuple(symbols[:count.value]), output))
        finally:
            self.compose_table_iterator_free(iterator)
        self.reference_symbols = {}
        reference = self.compile("us", "")
        try:
            for code in range(self.keymap_min_keycode(reference), self.keymap_max_keycode(reference) + 1):
                name = self.keymap_key_get_name(reference, code)
                if not name:
                    continue
                for group in range(self.keymap_num_layouts_for_key(reference, code)):
                    for level in range(self.keymap_num_levels_for_key(reference, code, group)):
                        self.reference_symbols[(name.decode(), group, level)] = self.raw_symbols(reference, code, group, level)
        finally:
            self.keymap_unref(reference)

    def close(self):
        self.compose_state_unref(self.compose_state)
        self.compose_table_unref(self.table)
        self.context_unref(self.context)

    def compile(self, layout, variant):
        names = RuleNames(b"evdev", b"pc105", layout.encode(), variant.encode(), b"")
        keymap = self.keymap_new_from_names(self.context, C.byref(names), 0)
        if not keymap:
            raise RuntimeError(f"Cannot compile {layout}({variant})")
        return keymap

    def symbols(self, state, keycode):
        symbols = C.POINTER(C.c_uint)()
        count = self.state_key_get_syms(state, keycode, C.byref(symbols))
        return tuple(symbols[:count])

    def raw_symbols(self, keymap, keycode, group, level):
        symbols = C.POINTER(C.c_uint)()
        count = self.keymap_key_get_syms_by_level(keymap, keycode, group, level, C.byref(symbols))
        return tuple(symbols[:count])

    def symbol_name(self, symbol):
        buf = C.create_string_buffer(128)
        self.keysym_get_name(symbol, buf, len(buf))
        return buf.value.decode()

    def text(self, symbols):
        codes = [self.keysym_to_utf32(symbol) for symbol in symbols]
        text = "".join(chr(code) for code in codes if code)
        return text if len(codes) == len([c for c in codes if c]) and text.isprintable() else ""

    def compose(self, sequence):
        self.compose_state_reset(self.compose_state)
        output = ""
        for symbols in sequence:
            if len(symbols) != 1:
                # XKB Compose does not support multi-keysym events.
                if self.compose_state_get_status(self.compose_state) != 0:
                    return None
                output += self.text(symbols)
                continue
            self.compose_state_feed(self.compose_state, symbols[0])
            status = self.compose_state_get_status(self.compose_state)
            if status == 0:
                output += self.text(symbols)
            elif status == 2:
                buf = C.create_string_buffer(1024)
                self.compose_state_get_utf8(self.compose_state, buf, len(buf))
                output += buf.value.decode()
                self.compose_state_reset(self.compose_state)
            elif status == 3:
                return None
        return output if self.compose_state_get_status(self.compose_state) == 0 else None


def read_catalog(source):
    entries = {}
    for filename in ("evdev.xml", "evdev.extras.xml"):
        tree = ET.parse(source / "rules" / filename)
        for layout in tree.findall(".//layoutList/layout"):
            config = layout.find("configItem")
            name = config.findtext("name")
            countries = [node.text for node in config.findall("countryList/iso3166Id")]
            for variant in [None] + layout.findall("variantList/variant"):
                info = config if variant is None else variant.find("configItem")
                variant_name = "" if variant is None else info.findtext("name")
                countries_here = [node.text for node in info.findall("countryList/iso3166Id")]
                entries.setdefault((name, variant_name), {
                    "layout": name, "variant": variant_name,
                    "description": info.findtext("description"),
                    "countries": countries_here or countries,
                })
    return sorted(entries.values(), key=lambda entry: (bool(entry["variant"]), entry["layout"], entry["variant"]))


def load_layout(path, root=ROOT):
    data = json.loads((root / path).read_text())
    merged = {section: {} for section in SECTIONS}
    if data.get("parent"):
        merged = load_layout(data["parent"], root)
    for section in SECTIONS:
        merged[section].update(data.get(section, {}))
    return merged


def format_json(data):
    """Keep compositions on one line, consistent with the existing files."""
    lines = ["{"]
    for i, (key, value) in enumerate(data.items()):
        comma = "," if i + 1 < len(data) else ""
        label = json.dumps(key)
        if isinstance(value, dict):
            lines.append(f"\t{label}: {{")
            for j, (k, v) in enumerate(value.items()):
                suffix = "," if j + 1 < len(value) else ""
                lines.append("\t\t" + json.dumps(k, ensure_ascii=False) + ": "
                             + json.dumps(v, ensure_ascii=False) + suffix)
            lines.append("\t}" + comma)
        elif key == "notes":
            lines.append(f"\t{label}: [")
            lines.extend("\t\t" + json.dumps(note, ensure_ascii=False)
                         + ("," if j + 1 < len(value) else "") for j, note in enumerate(value))
            lines.append("\t]" + comma)
        else:
            lines.append(f"\t{label}: " + json.dumps(value, ensure_ascii=False) + comma)
    return "\n".join(lines + ["}", ""])


def combo_cost(combo):
    return len(combo), combo


def sequence_cost(sequence):
    return len(sequence), sum(map(len, sequence)), sequence


class Imported:
    def __init__(self, xkb, entry):
        self.xkb, self.entry = xkb, entry
        self.keymap = xkb.compile(entry["layout"], entry["variant"])
        self.codes = {name: xkb.keymap_key_by_name(self.keymap, name.encode()) for name in POSITIONS}
        self.codes = {name: code for name, code in self.codes.items() if code != 0xFFFFFFFF}
        self.by_usage = {POSITIONS[name]: code for name, code in self.codes.items()}
        self.by_usage[0x31] = self.codes["BKSL"]
        self.state = xkb.state_new(self.keymap)
        self.events = {}
        self.reached = set()
        self.unreachable = []
        self.compositions = {}
        self.labels = {}
        self.raw = []
        self.build()

    def close(self):
        self.xkb.state_unref(self.state)
        self.xkb.keymap_unref(self.keymap)

    def build(self):
        xkb = self.xkb
        # Only momentary Shift/level/group selectors are safe as held keys.
        # Locks, latches, input methods and persistent group changes are not
        # simulated as Shift/AltGr. Their unavailable symbols are reported.
        selectors = {"Shift_L", "Shift_R", "ISO_Level3_Shift", "ISO_Level5_Shift",
                     "Mode_switch", "ISO_Group_Shift"}
        modifiers = []
        modifier_effects = set()
        baseline = {}
        for name, code in self.codes.items():
            symbols = xkb.symbols(self.state, code)
            baseline[name] = symbols
            if len(symbols) == 1 and xkb.symbol_name(symbols[0]) in selectors:
                state = xkb.state_new(self.keymap)
                try:
                    xkb.state_update_key(state, code, 1)
                    effect = (xkb.state_serialize_mods(state, 8), xkb.state_serialize_layout(state, 128))
                    if effect != (0, 0) and effect not in modifier_effects:
                        modifiers.append(name)
                        modifier_effects.add(effect)
                finally:
                    xkb.state_unref(state)
        modifiers.sort(key=lambda name: (name != "LFSH", name != "RALT", name))
        for count in range(min(3, len(modifiers)) + 1):
            for held in itertools.combinations(modifiers, count):
                state = xkb.state_new(self.keymap)
                try:
                    for name in held:
                        xkb.state_update_key(state, self.codes[name], 1)
                    for name, code in self.codes.items():
                        if name in held:
                            continue
                        symbols = xkb.symbols(state, code)
                        group = xkb.state_key_get_layout(state, code)
                        level = xkb.state_key_get_level(state, code, group)
                        self.reached.add((name, group, level))
                        combo = tuple("XKB_" + key for key in held + (name,))
                        if symbols and (symbols not in self.events or combo_cost(combo) < combo_cost(self.events[symbols])):
                            self.events[symbols] = combo
                finally:
                    xkb.state_unref(state)
        for symbols, combo in self.events.items():
            output = xkb.compose([symbols])
            if output and output.isprintable():
                self.add_composition(output, [combo])
        single = {symbols[0]: combo for symbols, combo in self.events.items() if len(symbols) == 1}
        for symbols, output in xkb.entries:
            if all(symbol in single for symbol in symbols):
                self.add_composition(output, [single[symbol] for symbol in symbols])
        used_labels = set()
        base = json.loads((ROOT / "base/base.json").read_text())
        canonical = {char: base["to_hid_keyboard"][usage]
                     for char, usage in base["from_hid_keyboard"].items()
                     if len(char) == 1 and char.isascii()}
        canonical[" "] = "Space"
        for name, symbols in baseline.items():
            text = xkb.text(symbols)
            label = canonical.get(text, text.upper()) if text else " + ".join(xkb.symbol_name(s) for s in symbols)
            label = label or "NoSymbol"
            if label.casefold() in used_labels:
                label += " [" + name + "]"
            used_labels.add(label.casefold())
            self.labels[name] = label
        self.arrangement = "".join(xkb.text(baseline.get(name, ())).lower()
                                   for name in ("AD01", "AD02", "AD03", "AD04", "AD05", "AD06"))
        for name, code in self.codes.items():
            # Report printable/dead/multi-key symbols unavailable through held
            # modifiers, including additional groups. Keypad NumLock layers are
            # conventional lock state, not part of text composition here.
            for group in range(xkb.keymap_num_layouts_for_key(self.keymap, code)):
                for level in range(xkb.keymap_num_levels_for_key(self.keymap, code, group)):
                    symbols = xkb.raw_symbols(self.keymap, code, group, level)
                    self.raw.append((name, group, level, symbols))
                    if name.startswith("KP"):
                        continue
                    if (name, group, level) in self.reached:
                        continue
                    interesting = xkb.text(symbols) or any(xkb.symbol_name(s).startswith("dead_") for s in symbols)
                    if interesting and symbols not in self.events:
                        self.unreachable.append(f"{name}:group{group + 1}:level{level + 1}")
        mapped_codes = set(self.codes.values())
        for code in range(xkb.keymap_min_keycode(self.keymap), xkb.keymap_max_keycode(self.keymap) + 1):
            if code in mapped_codes:
                continue
            name = xkb.keymap_key_get_name(self.keymap, code)
            if not name:
                continue
            for group in range(xkb.keymap_num_layouts_for_key(self.keymap, code)):
                for level in range(xkb.keymap_num_levels_for_key(self.keymap, code, group)):
                    symbols = xkb.raw_symbols(self.keymap, code, group, level)
                    interesting = xkb.text(symbols) or any(xkb.symbol_name(s).startswith("dead_") for s in symbols)
                    if interesting:
                        self.raw.append((name.decode(), group, level, symbols))
                        # Generic evdev multimedia/calculator extensions are
                        # not locale-specific hardware. Report actual overrides.
                        if symbols != xkb.reference_symbols.get((name.decode(), group, level)):
                            self.unreachable.append(f"unmapped:{name.decode()}:group{group + 1}:level{level + 1}")
        self.verify(self.compositions, {"XKB_" + name: f"0x{POSITIONS[name]:02X}" for name in self.codes})

    def add_composition(self, output, sequence):
        if output not in self.compositions or sequence_cost(sequence) < sequence_cost(self.compositions[output]):
            self.compositions[output] = sequence

    def verify(self, compositions, aliases):
        """Replay complete sequences through physical key presses + Compose."""
        aliases = {name.casefold(): int(usage, 16) for name, usage in aliases.items()}
        for output, sequence in compositions.items():
            if sequence is None:
                continue
            state = self.xkb.state_new(self.keymap)
            events = []
            try:
                for combo in sequence:
                    codes = [self.by_usage.get(aliases[key.casefold()]) for key in combo]
                    if any(code is None for code in codes):
                        raise AssertionError(f"Unmapped physical key: {combo}")
                    for code in codes[:-1]:
                        self.xkb.state_update_key(state, code, 1)
                    events.append(self.xkb.symbols(state, codes[-1]))
                    self.xkb.state_update_key(state, codes[-1], 1)
                    self.xkb.state_update_key(state, codes[-1], 0)
                    for code in reversed(codes[:-1]):
                        self.xkb.state_update_key(state, code, 0)
                actual = self.xkb.compose(events)
                if actual != output:
                    raise AssertionError(f"{self.entry}: {output!r} -> {actual!r}: {sequence}")
            finally:
                self.xkb.state_unref(state)

    def make_layout(self, parent_path, parent, version):
        aliases = dict(parent["from_hid_keyboard"])
        physical = {"XKB_" + name: f"0x{POSITIONS[name]:02X}" for name in self.codes}
        aliases.update(physical)
        for name, label in self.labels.items():
            aliases[label] = f"0x{POSITIONS[name]:02X}"
        to_hid = {f"0x{POSITIONS[name]:02X}": label for name, label in self.labels.items()}
        to_hid["0x31"] = to_hid["0x32"]
        # Remove every inherited composition that cannot be emitted by this
        # layout. Parent aliases can change meaning, so compare physical events.
        compositions = dict(self.compositions)
        def resolve(sequence):
            folded = {key.casefold(): value for key, value in aliases.items()}
            return [[folded.get(key.casefold(), "unresolved:" + key) for key in combo] for combo in sequence]
        for output, sequence in parent["composition"].items():
            if output not in compositions:
                compositions[output] = None
            elif sequence is not None and resolve(sequence) == resolve(compositions[output]):
                del compositions[output]
        entry = self.entry
        identity = entry["layout"] + ("(" + entry["variant"] + ")" if entry["variant"] else "")
        notes = [MARKER, entry["description"],
                 f"Source: installed xkb-data {version}; /usr/share/X11/xkb/symbols/{entry['layout']} ({identity}).",
                 "Rules: evdev; model: pc105; no XKB options or personal overrides.",
                 "Compose: /usr/share/X11/locale/en_US.UTF-8/Compose (system UTF-8 table).",
                 "XKB_* aliases identify physical USB keys; combinations use momentary selectors."]
        if self.unreachable:
            notes.append("Some symbols require locks, latches or group switching; see tools/xkb-catalog.tsv.")
        data = {
            "name": ["xkb:" + identity], "authors": [], "notes": notes,
            "locale": entry["countries"] or ["None"],
            "hid_locale": HID_LOCALES.get(entry["layout"], "Undefined"),
            "parent": parent_path,
            "to_hid_keyboard": {k: v for k, v in to_hid.items() if parent["to_hid_keyboard"].get(k) != v},
            "from_hid_keyboard": {k: v for k, v in aliases.items() if parent["from_hid_keyboard"].get(k) != v},
            "composition": dict(sorted(compositions.items())),
        }
        merged = {section: dict(parent[section], **data[section]) for section in SECTIONS}
        if any(value is None for value in merged["composition"].values()):
            raise AssertionError("Generated layouts must not need null composition removals")
        self.verify(merged["composition"], merged["from_hid_keyboard"])
        return data, merged


